'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('verification.js','utf8');
const context=vm.createContext({window:{WorshipCharts:{all:()=>({})}}});
const beg=source.indexOf('const STUDY_SHEETS=['),end=source.indexOf('let studyModal=null');
assert.ok(beg>0&&end>beg,'Study-sheet source section must exist');
const setup=[
 source.match(/const norm=.*?;\n/)[0],
 source.match(/const normalizedTitle=.*?;\n/)[0],
 source.match(/const SOURCES=.*?;\n/)[0],
 source.match(/function recordingId[^\n]+/)[0],
 source.match(/function candidates[^\n]+/)[0],
 'function entry(t){return t.review||{}}',
 'function state(t){return t.review?.status||""}',
 'function getSource(t){return t.sources||candidates(t)}',
 source.slice(beg,end)
].join('\n');
vm.runInContext(setup,context);
const t=(id,n,title,artist)=>({spotify:'https://open.spotify.com/track/'+id,n,key:id+'#'+n,title,artist,album:'Album'});
for(const [id,n,title,artist] of [
 ['7dfkOys2ycCJcqHHLbcKMt',1,'Victoria','Abel Brito'],
 ['3YXYBATD78SlSo0OtB4LkR',2,'Entonces La Iglesia Se Alegrara en La Danza','Alabanzas Cristianas Ebenezer'],
 ['3GfRe2Ftsm33pv53c5dLt0',3,'Las Riquezas y Gloria Proceden Ti','Alabanzas Cristianas Ebenezer']
]){
 context.t=t(id,87,title,artist);
 assert.equal(vm.runInContext('studySheet(t).n',context),n,'Study sheet uses Spotify ID, not playlist index');
 assert.equal(vm.runInContext('candidates(t).length',context),1,'Exact-ID source matched independently of playlist order');
}
context.t=t('anotherRecording',1,'Victoria','Abel Brito');
assert.equal(vm.runInContext('studySheet(t)',context),null,'Different recording cannot inherit a sheet');
// The test below references the same registry in the original VM without moving objects across contexts.
context.t=t('3GfRe2Ftsm33pv53c5dLt0',3,'Las Riquezas y Gloria Proceden Ti','Alabanzas Cristianas Ebenezer');
assert.equal(vm.runInContext('studySheet(t).chords.length',context),5);
assert.equal(vm.runInContext('studySheet(t).sets.length',context),4);
assert.equal(vm.runInContext('studySheet(t).chords.every(ch=>!!STUDY_SHAPES[ch])',context),true);

context.t={...t('dynamic1',17,'Synthetic example','Example'),review:{status:'approved'},sources:[{url:'https://acordes.lacuerda.net/example/song.shtml',site:'LaCuerda',key:'C',preview:'Intro: C G Am F\nChorus: F G C'}]};
assert.equal(vm.runInContext('studySheet(t).autoGenerated && studySheet(t).chords.length===4',context),true);
context.t={...t('dynamic2',18,'Synthetic example','Example'),review:{status:'approved'},sources:[{url:'https://acordes.lacuerda.net/example/song.shtml',site:'LaCuerda'}]};
assert.equal(vm.runInContext('studySheet(t).hasMusic',context),false,'URL alone cannot supply chord notes');
context.t={...t('dynamic3',19,'Synthetic example','Example'),review:{status:''},sources:[{url:'https://acordes.lacuerda.net/example/song.shtml',site:'LaCuerda',preview:'Intro: C G Am F'}]};
assert.equal(vm.runInContext('studySheet(t)',context),null,'Source found does not mean approved');
context.t={...t('dynamic4',20,'Synthetic medley','Example'),review:{status:'approved'},sources:[{url:'https://acordes.lacuerda.net/example/section.shtml',site:'LaCuerda',preview:'Intro: C G F',sourceCheck:{scope:'section-only'}}]};
assert.equal(vm.runInContext('studySheet(t)',context),null,'Partial medley sources rejected');

vm.runInContext(fs.readFileSync('backup.js','utf8'),context);
assert.throws(()=>vm.runInContext("validateBackup({app:'Worship Chords Full Backup',version:1,values:{'worship-spotify-pkce-auth-v1':'secret'}})",context));
assert.throws(()=>vm.runInContext("validateBackup({app:'Worship Chords Full Backup',version:1,values:{'worship-chords-favorites-v1':'{}'}})",context));
vm.runInContext("validateBackup({app:'Worship Chords Full Backup',version:1,values:{'worship-chords-favorites-v1':'[\"track#1\"]'}})",context);
const data=new Map([['a','old']]);let failed=false;
context.storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>{if(k==='b'&&!failed){failed=true;throw Error('quota')}data.set(k,v)},removeItem:k=>data.delete(k)};
assert.throws(()=>vm.runInContext("restoreBackup(storage,{a:'new',b:'new'})",context));assert.equal(data.get('a'),'old');assert.equal(data.has('b'),false);
const repoSources=JSON.parse(fs.readFileSync('source-candidates.json','utf8'));
for(const id of ['7dfkOys2ycCJcqHHLbcKMt','3YXYBATD78SlSo0OtB4LkR']){
 const inApp=vm.runInContext('SOURCES',context).find(s=>s.spotifyTrackId===id),inJson=repoSources.find(s=>s.spotifyTrackId===id);
 assert.deepEqual({...inApp.verification},{status:'verified',label:'Recording verified by you',date:'2026-10-21'});
 assert.deepEqual({...inApp.verification},inJson.verification);
}
assert.equal(vm.runInContext('SOURCES',context).filter(s=>s.verification).length,2);
console.log('Passed: exact Spotify recording identity, 003 guitar diagrams, approved auto-sheets, incomplete medley exclusions, backup validation and rollback.');
